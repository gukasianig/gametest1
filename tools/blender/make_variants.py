"""Концепт-варианты врагов в 4 темах (НЕ роботы) для выбора: A жуки-пришельцы, B нежить, C слизни-мутанты, D монстры.
По 3 роли в каждой теме: слабый, быстрый, танк. Только превью (docs/art/variants), FBX не создаются.
Запуск: blender -b -P make_variants.py  (PREVIEW_DIR — куда писать превью)."""
import math
import os
import sys
sys.path.insert(0, os.path.dirname(__file__))
import kit

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "Assets", "Art", "Generated"))
PREVIEW = os.environ.get("PREVIEW_DIR", os.path.join(os.path.dirname(__file__), "..", "..", "docs", "art", "variants"))
os.makedirs(PREVIEW, exist_ok=True)
# палитра: 0 сталь 1 тёмная 2 красный 3 оранжевый 4 жёлтый 5 фиолет 6 зелёный 7 бирюза 8 белый 9 синий 10 чёрный 11 коричн 12 ср.сталь 13 розовый 14 т.фиолет 15 лайм


def make(name, build, size=2.6):
    kit.clear_scene()
    p = os.path.join(OUT, "Palette.png")
    kit.save_palette(p)
    mat = kit.make_material(p)
    root = kit.make_root(name)
    b = kit.Builder(name)
    build(b)
    o = b.finish(parent=root)
    o.data.materials.append(mat)
    kit.render_preview([o], os.path.join(PREVIEW, name + ".png"), yaw_deg=35, elev_deg=25, size=size)
    print("DONE", name)


def eyes(b, y, z, dx=0.16, r=0.09, c=8, pupil=10):
    for sx in (-1, 1):
        b.sphere((sx * dx, y, z), r, c)
        b.sphere((sx * dx, y + r * 0.7, z), r * 0.5, pupil)


def six_legs(b, w, length, z, c, thick=0.08):
    for sx in (-1, 1):
        for i in (-0.3, 0, 0.3):
            b.box((sx * (w + length / 2), i, z), (length, thick, thick), c, bevel=0.01)
            b.box((sx * (w + length), i, z / 2), (thick, thick, z), c, bevel=0.01)



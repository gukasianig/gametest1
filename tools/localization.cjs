// Usage: node tools/localization.cjs [--inventory|--extract|--generate]. Verifies languages and source coverage.
const fs = require('node:fs');
const cp = require('node:child_process');
const path = require('node:path');
const ru = /[А-Яа-яЁё]/;
function literals(source) {
    const result = [];
    const tokens = /\/\/[^\n]*|\/\*[\s\S]*?\*\/|'(?:\\.|[^'\\])*'|@"(?:""|[^"])*"|"(?:\\.|[^"\\])*"/g;
    for (const match of source.matchAll(tokens)) {
        if (!match[0].startsWith('"') || !ru.test(match[0])) continue;
        const line = source.slice(source.lastIndexOf('\n', match.index) + 1, match.index);
        if (/\[(?:Header|Tooltip)|Debug\.(?:Log|LogWarning|LogError)\(/.test(line)) continue;
        result.push({ value: JSON.parse(match[0]), start: match.index, end: match.index + match[0].length });
    }
    return result;
}
const sources = new Map();
for (const file of fs.readdirSync('Assets/scripts').filter(f => f.endsWith('.cs')).sort()) {
    if (file === 'GameText.cs' || file === 'GameTextSources.cs') continue;
    for (const item of literals(fs.readFileSync('Assets/scripts/' + file, 'utf8'))) {
        if (!sources.has(item.value)) sources.set(item.value, file.replace('.cs', ''));
    }
}
// Read only text-bearing YAML fields and their continuation lines, never entire Unity assets.
const yamlFiles = ['Assets/Scenes/GreenArenaPlay.unity', 'Assets/Settings/UpgradeCatalog.asset'];
const yaml = cp.execFileSync('rg', ['-N', '--no-filename', '-A', '5', '^ *(weaponName|title|role|description|m_Text):', ...yamlFiles], {encoding:'utf8'});
for (const match of yaml.matchAll(/^ *(?:weaponName|title|role|description|m_Text): ("(?:[^"\\]|\\.|\n)*")/gm)) {
    const value = JSON.parse(match[1].replace(/\r?\n\s*/g, ' '));
    if (ru.test(value) && !sources.has(value)) sources.set(value, 'Serialized');
}
for (const match of yaml.matchAll(/^ *(?:weaponName|title|role|description|m_Text): ([^"\r\n][^\r\n]*)/gm)) {
    const value = match[1].trim();
    if (ru.test(value) && !sources.has(value)) sources.set(value, 'Serialized');
}
const entries = [...sources].map(([value, context], i) => ({id: context.toLowerCase() + '.' + String(i + 1).padStart(3,'0'), ru: value, en: ''}));
if (process.argv.includes('--inventory')) {
    fs.mkdirSync('Logs', {recursive:true});
    fs.writeFileSync('Logs/localization-inventory.json', JSON.stringify({entries}, null, 2));
    entries.forEach((e,i) => console.log(`${i + 1}\t${JSON.stringify(e.ru)}`));
} else {
    const catalog = JSON.parse(fs.readFileSync('Assets/Resources/Localization/game-text.json', 'utf8'));
    const known = new Map(catalog.entries.map(e => [e.ru, e]));
    const ids = new Set();
    let errors = 0;
    for (const e of catalog.entries) {
        if (!e.id || ids.has(e.id) || !e.ru || !e.en || ru.test(e.en)) {console.error('Invalid entry:', e.id); errors++;}
        ids.add(e.id);
        const tags = s => (s.match(/<[^>]+>/g) || []).join('|');
        if (tags(e.ru) !== tags(e.en)) {console.error('Rich text mismatch:', e.id); errors++;}
    }
    if (known.size !== catalog.entries.length) {console.error('Duplicate Russian sources.'); errors++;}
    const generatedPath = 'Assets/scripts/GameTextSources.cs';
    const generated = '// Generated by node tools/localization.cjs --generate from game-text.json. Do not edit.\n' +
        '// Pure managed data: safe in Unity serialization/static constructors before Awake.\n' +
        'using System.Collections.Generic;\n\ninternal static class GameTextSources\n{\n' +
        '    internal static readonly Dictionary<string, string> Values = new Dictionary<string, string>\n    {\n' +
        catalog.entries.map(e => `        { ${JSON.stringify(e.id)}, ${JSON.stringify(e.ru)} },`).join('\n') + '\n    };\n}\n';
    if (process.argv.includes('--generate')) fs.writeFileSync(generatedPath, generated);
    else if (!fs.existsSync(generatedPath) || fs.readFileSync(generatedPath,'utf8') !== generated) {
        console.error('Canonical text data is stale. Run node tools/localization.cjs --generate.'); errors++;
    }
    for (const e of entries) if (!known.has(e.ru)) {console.error('Missing translation:', JSON.stringify(e.ru)); errors++;}
    for (const file of fs.readdirSync('Assets/scripts').filter(f => f.endsWith('.cs'))) {
        const filename = path.join('Assets/scripts', file);
        let source = fs.readFileSync(filename, 'utf8');
        for (const match of source.matchAll(/GameText\.Source\("([^"]+)"\)/g)) {
            if (!ids.has(match[1])) {console.error('Unknown text ID:', file, match[1]); errors++;}
        }
        if (process.argv.includes('--extract') && file !== 'GameText.cs' && file !== 'GameTextSources.cs') {
            for (const item of literals(source).reverse()) {
                const entry = known.get(item.value);
                if (entry) source = source.slice(0, item.start) + `GameText.Source("${entry.id}")` + source.slice(item.end);
            }
            // These public constants are canonical text now supplied by the resource catalog.
            source = source.replace(/public const string (CurrencyName|Title) = GameText/g, 'public static readonly string $1 = GameText');
            if (source !== fs.readFileSync(filename,'utf8')) fs.writeFileSync(filename, source);
        }
    }
    console.log(`${catalog.entries.length} bilingual entries; ${entries.length} source strings; ${errors} errors.`);
    process.exitCode = errors ? 1 : 0;
}
